def config_roots() -> list[tuple[str, type]]:
    from platoon.eval.run import PlatoonEvalConfig
    from platoon.train.config_defs import PlatoonTinkerRLTrainerConfig

    return [("training", PlatoonTinkerRLTrainerConfig), ("evaluation", PlatoonEvalConfig)]


def _is_pydantic(cls: Any) -> bool:
    return isinstance(cls, type) and hasattr(cls, "model_fields") and hasattr(cls, "model_validate")


def _is_schema(cls: Any) -> bool:
    return isinstance(cls, type) and (dataclasses.is_dataclass(cls) or _is_pydantic(cls))


@dataclasses.dataclass
class ConfigField:
    name: str
    annotation: Any
    default: str
    doc: str


def config_fields(cls: type) -> list[ConfigField]:
    docs = class_member_docs(cls)
    if _is_pydantic(cls):
        found = []
        for name, info in typing.cast(Any, cls).model_fields.items():
            if info.is_required():
                default = "required"
            elif info.default_factory is not None:
                default = _default_text(info.default_factory())
            else:
                default = _default_text(info.default)
            doc = _with_deprecation(cls, name, info.description or docs.get(name, ""))
            found.append(ConfigField(info.alias or name, info.annotation, default, doc))
        return found
    hints = typing.get_type_hints(cls)
    # A free-form mapping that the loader checks against a schema of its own is documented as that schema.
    schemas = getattr(cls, "FIELD_SCHEMAS", None) or {}
    found = []
    for item in dataclasses.fields(typing.cast(Any, cls)):
        if not item.init:
            continue
        if item.default is not dataclasses.MISSING:
            default = _default_text(item.default)
        elif item.default_factory is not dataclasses.MISSING:
            default = _default_text(item.default_factory())
        else:
            default = "required"
        doc = _with_deprecation(cls, item.name, docs.get(item.name, ""))
        found.append(ConfigField(item.name, schemas.get(item.name, hints.get(item.name, Any)), default, doc))
    return found


def _with_deprecation(cls: type, name: str, doc: str) -> str:
    """A key's description, which for a key the class names as deprecated (``DEPRECATED_KEYS``,
    ``platoon.deprecations``) starts with what replaces it and the release that removes it."""

    from platoon.deprecations import deprecated_keys

    deprecated = deprecated_keys(cls).get(name)
    if deprecated is None:
        return doc
    replacement = f"``{deprecated.renamed_to}``" if deprecated.renamed_to is not None else deprecated.instead
    marker = f"**Deprecated:** use {replacement} instead; platoon {deprecated.removed_in} removes it."
    return f"{marker} {doc}" if doc else marker


def _value_text(value: Any) -> str:
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        cls = type(value)
        base = cls()
        changed = [
            f"{item.name}={_value_text(getattr(value, item.name))}"
            for item in dataclasses.fields(value)
            if item.init and getattr(value, item.name) != getattr(base, item.name)
        ]
        return f"{cls.__name__}({', '.join(changed)})"
    if _is_pydantic(type(value)):
        return f"{type(value).__name__}(...)"
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_value_text(item) for item in value) + "]"
    if isinstance(value, Mapping):
        return "{" + ", ".join(f"{json.dumps(str(key))}: {_value_text(item)}" for key, item in value.items()) + "}"
    if isinstance(value, float) and value.is_integer() and abs(value) < 1e15:
        return f"{value:.1f}"
    try:
        return json.dumps(value)
    except TypeError:
        return repr(value)


def _default_text(value: Any) -> str:
    return f"`{_value_text(value)}`"


def _schema_classes(annotation: Any) -> Iterator[tuple[type, str]]:
    """The config classes inside ``annotation``, each with the path suffix that reaches it (``""``, ``.<i>`` for
    a list item, ``.<key>`` for a mapping value)."""

    origin = typing.get_origin(annotation)
    if origin is typing.Annotated:
        yield from _schema_classes(typing.get_args(annotation)[0])
    elif _is_schema(annotation):
        yield annotation, ""
    elif origin in (typing.Union, types.UnionType):
        for member in typing.get_args(annotation):
            yield from _schema_classes(member)
    elif origin in (list, tuple, set, frozenset, typing.get_origin(typing.Sequence[int])):
        for member in typing.get_args(annotation):
            for found, suffix in _schema_classes(member):
                yield found, ".<i>" + suffix
    elif origin in (dict, typing.get_origin(typing.Mapping[str, int])):
        args = typing.get_args(annotation)
        if len(args) == 2:
            for found, suffix in _schema_classes(args[1]):
                yield found, ".<key>" + suffix


def config_classes() -> tuple[list[type], dict[type, list[tuple[str, str]]]]:
    """The config classes in breadth-first order from the roots, and every ``(root, dotted path)`` of each."""

    order: list[type] = []
    paths: dict[type, list[tuple[str, str]]] = {}
    for root, root_class in config_roots():
        queue: list[tuple[type, str, tuple[type, ...]]] = [(root_class, "", ())]
        while queue:
            cls, path, ancestors = queue.pop(0)
            if cls not in paths:
                order.append(cls)
                paths[cls] = []
            if path and (root, path) not in paths[cls]:
                paths[cls].append((root, path))
            for item in config_fields(cls):
                for nested, suffix in _schema_classes(item.annotation):
                    if nested not in (*ancestors, cls):
                        nested_path = f"{path}.{item.name}{suffix}" if path else f"{item.name}{suffix}"
                        queue.append((nested, nested_path, (*ancestors, cls)))
    return order, paths


def _config_titles(classes: list[type]) -> dict[type, str]:
    names = [cls.__name__ for cls in classes]
    return {
        cls: cls.__name__ if names.count(cls.__name__) == 1 else f"{cls.__name__} ({cls.__module__})" for cls in classes
    }


def _config_type_text(annotation: Any, links: Mapping[type, str]) -> str:
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if annotation is type(None) or annotation is None:
        return "None"
    if annotation is Any:
        return "Any"
    if annotation is Ellipsis:  # tuple[X, ...]
        return "..."
    if origin is typing.Annotated:
        return _config_type_text(args[0], links)
    if origin is typing.Literal:
        return " | ".join(json.dumps(value) for value in args)
    if origin in (typing.Union, types.UnionType):
        members = sorted(args, key=lambda member: member is type(None))
        return " | ".join(_config_type_text(member, links) for member in members)
    if annotation in links:
        return links[annotation]
    if origin is not None:
        name = getattr(origin, "__name__", str(origin))
        return f"{name}[{', '.join(_config_type_text(arg, links) for arg in args)}]"
    if isinstance(annotation, type):
        return annotation.__name__
    return str(annotation).replace("typing.", "")


def render_config() -> str:
    classes, paths = config_classes()
    titles = _config_titles(classes)
    anchors = {cls: anchor(titles[cls]) for cls in classes}
    roots = dict((cls, root) for root, cls in config_roots())
    links = {cls: f"[{cls.__name__}](#{anchors[cls]})" for cls in classes}
    lines = [
        GENERATED,
        "",
        "# Config reference",
        "",
        "`platoon train` reads a training config and `platoon eval` an evaluation config. Both are YAML files "
        "whose keys are the fields of the config classes below: the top level of a training config is "
        f"[`{titles[classes[0]]}`](#{anchors[classes[0]]}), and the top level of an evaluation config is "
        + ", ".join(f"[`{titles[cls]}`](#{anchors[cls]})" for cls, root in roots.items() if root == "evaluation")
        + ". A key that is not a field, or a value of the wrong type, fails validation with its dotted path.",
        "",
        "Each section documents one config class: where it appears in a config file, then one row per key with "
        "its type, its default (`required` when it has none) and what it does. Paths use the override syntax: "
        "`environments.<i>` is any item of the `environments` list and `.<key>` any key of a mapping. "
        "`platoon config show CONFIG --defaults` prints a config with every default filled in, and "
        "`platoon config validate CONFIG` checks one. Plugins that subclass the training config (an environment's "
        "`trainer_config`) add sections of their own, which they document.",
        "",
        "A section that a config gives in part keeps its field's default for the keys it leaves out, not its "
        "class's: an `eval.workflow_config` that sets only `rollout_config` keeps the `group_size: 1` and the "
        "filters off that the default below shows. A free-form mapping, such as `train.loss_fn_config`, replaces "
        "its default whole.",
        "",
        _upkeep("the config classes"),
        "",
        "## Contents",
        "",
    ]
    lines += [f"- [`{titles[cls]}`](#{anchors[cls]})" for cls in classes]
    for cls in classes:
        where = []
        if cls in roots:
            where.append(f"The top level of {'a' if roots[cls] == 'training' else 'an'} {roots[cls]} config.")
        for root in ("training", "evaluation"):
            found = [path for path_root, path in paths[cls] if path_root == root]
            if found:
                article = "a" if root == "training" else "an"
                where.append(f"In {article} {root} config: " + ", ".join(f"`{path}`" for path in found) + ".")
        lines += [
            "",
            f'<a id="{anchors[cls]}"></a>',
            "",
            f"## {titles[cls]}",
            "",
            f"`{cls.__module__}.{cls.__qualname__}`",
        ]
        lines += ["", " ".join(where)] if where else []
        doc = markdown(inspect.getdoc(cls) if cls.__doc__ and not cls.__doc__.startswith(cls.__name__ + "(") else "")
        if doc:
            lines += ["", doc]
        lines += ["", "| Key | Type | Default | Description |", "|---|---|---|---|"]
        for item in config_fields(cls):
            type_text = _config_type_text(item.annotation, links).replace("|", "\\|")
            lines.append(f"| `{item.name}` | {type_text} | {item.default} | {cell(item.doc)} |")
    lines += _task_samplers(links)
    lines += _group_admissions(links)
    lines += _trainers(links)
    lines += _credit_estimators(links)
    return "\n".join(lines).rstrip() + "\n"


