def _annotation_text(annotation: Any) -> str:
    if isinstance(annotation, typing.ForwardRef):  # a NamedTuple's string annotation
        annotation = annotation.__forward_arg__
    if isinstance(annotation, str):
        return annotation
    return inspect.formatannotation(annotation).replace("typing.", "").replace("collections.abc.", "")


def _default_repr(value: Any) -> str:
    if isinstance(value, str):
        return json.dumps(value)
    return "<factory>" if repr(value) == "<factory>" else repr(value)


def signature_text(prefix: str, name: str, fn: Callable[..., Any], *, drop_first: bool = False) -> str:
    """``prefix name(params) -> return``, one parameter per line when it does not fit on one."""

    signature = inspect.signature(fn)
    params = list(signature.parameters.values())
    if drop_first and params and params[0].name in ("self", "cls"):
        params = params[1:]
    parts: list[str] = []
    star = False
    for index, param in enumerate(params):
        if param.kind is param.KEYWORD_ONLY and not star:
            parts.append("*")
            star = True
        if param.kind is param.VAR_POSITIONAL:
            star = True
        text = {param.VAR_POSITIONAL: "*", param.VAR_KEYWORD: "**"}.get(param.kind, "") + param.name
        if param.annotation is not param.empty:
            text += ": " + _annotation_text(param.annotation)
        if param.default is not param.empty:
            text += (" = " if param.annotation is not param.empty else "=") + _default_repr(param.default)
        parts.append(text)
        following = params[index + 1] if index + 1 < len(params) else None
        if param.kind is param.POSITIONAL_ONLY and (following is None or following.kind is not param.POSITIONAL_ONLY):
            parts.append("/")
    returns = ""
    if signature.return_annotation is not signature.empty:
        returns = " -> " + _annotation_text(signature.return_annotation)
    line = f"{prefix}{name}({', '.join(parts)}){returns}"
    if len(line) <= MAX_SIGNATURE:
        return line
    return f"{prefix}{name}(\n" + "".join(f"    {part},\n" for part in parts) + f"){returns}"


def _fenced(code: str) -> list[str]:
    return ["```python", code, "```"]


def _is_alias(value: Any) -> bool:
    return typing.get_origin(value) is not None or isinstance(value, typing.TypeAliasType)


def _alias_source(module: types.ModuleType, name: str) -> str | None:
    """The assignment that defines ``name`` in ``module``, as the source writes it (so it stays ruff-formatted)."""

    source = inspect.getsource(module)
    for node in ast.parse(source).body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return ast.get_source_segment(source, node)
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.target.id == name:
            return ast.get_source_segment(source, node)
    return None


def _defining_module(name: str, value: Any) -> types.ModuleType:
    import platoon

    exports: dict[str, str] = getattr(platoon, "_EXPORTS")
    module_name = exports.get(name) or getattr(value, "__module__", None)
    if not module_name:
        raise ValueError(f"Cannot tell which module defines platoon.{name}")
    return sys.modules[module_name] if module_name in sys.modules else __import__(module_name, fromlist=["_"])


def _class_doc(cls: type) -> str:
    doc = cls.__doc__ or ""
    if dataclasses.is_dataclass(cls) and doc.startswith(cls.__name__ + "("):
        return ""  # the docstring dataclasses generate
    return markdown(inspect.getdoc(cls))


def _factory_text(factory: Callable[[], Any]) -> str:
    """A ``default_factory`` default: an empty container or a dataclass built with its defaults; ``generated``
    for any other factory, whose value may differ per call (a fresh id, say)."""

    if factory in (dict, list, set, tuple) or (isinstance(factory, type) and dataclasses.is_dataclass(factory)):
        return f"`{_default_repr(factory())}`"
    return "generated"


def _members(cls: type) -> list[tuple[str, Any]]:
    return [(name, value) for name, value in vars(cls).items() if not name.startswith("_")]


def render_object(title: str, value: Any, module: types.ModuleType, level: int, prefix: str) -> list[str]:
    """One exported object: its signature, docstring and public members."""

    hashes = "#" * level
    name = title.rsplit(".", 1)[-1]
    lines = ["", f'<a id="{anchor(title)}"></a>', "", f"{hashes} `{title}`", ""]
    if isinstance(value, type):
        bases = [base for base in value.__bases__ if base is not object]
        base_text = ", ".join("Protocol" if base is typing.Protocol else base.__name__ for base in bases)
        if typing.Protocol in value.__mro__ and "Protocol" not in base_text:
            base_text = ", ".join(filter(None, [base_text, "Protocol"]))
        lines += _fenced(f"class {name}({base_text})" if base_text else f"class {name}")
        doc = _class_doc(value)
        if doc:
            lines += ["", doc]
        lines += _class_members(value, level)
    elif callable(value) and not _is_alias(value):
        keyword = "async def " if inspect.iscoroutinefunction(value) else "def "
        lines += _fenced(signature_text(keyword, name, value))
        doc = markdown(inspect.getdoc(value))
        if doc:
            lines += ["", doc]
    else:
        source = _alias_source(module, name) or f"{name} = {value!r}"
        lines += _fenced(source)
        doc = member_docs(module).get(name, "")
        if doc:
            lines += ["", markdown(doc)]
    return lines


def _class_members(cls: type, level: int) -> list[str]:
    docs = class_member_docs(cls)
    lines: list[str] = []
    rows: list[str] = []
    if dataclasses.is_dataclass(cls):
        hints = {item.name: item.type for item in dataclasses.fields(cls)}
        for item in dataclasses.fields(cls):
            if item.name.startswith("_"):  # private: neither a field to set nor one to read
                continue
            if item.default is not dataclasses.MISSING:
                default = f"`{_default_repr(item.default)}`"
            elif item.default_factory is not dataclasses.MISSING:
                default = _factory_text(item.default_factory)
            else:
                default = "required"
            type_text = cell(_annotation_text(hints[item.name]))
            rows.append(f"| `{item.name}` | `{type_text}` | {default} | {cell(docs.get(item.name))} |")
        header = ["| Field | Type | Default | Description |", "|---|---|---|---|"]
    else:
        for name, annotation in inspect.get_annotations(cls).items():
            if not name.startswith("_"):
                rows.append(f"| `{name}` | `{cell(_annotation_text(annotation))}` | {cell(docs.get(name))} |")
        header = ["| Attribute | Type | Description |", "|---|---|---|"]
    properties = [(name, value) for name, value in _members(cls) if isinstance(value, property)]
    for name, value in properties:
        returns = inspect.signature(value.fget).return_annotation if value.fget else inspect.Signature.empty
        type_text = "" if returns is inspect.Signature.empty else f"`{cell(_annotation_text(returns))}`"
        doc = cell(inspect.getdoc(value)) + (" Read-only." if value.fset is None else "")
        rows.append(f"| `{name}` | {type_text} | {'| ' if dataclasses.is_dataclass(cls) else ''}{doc.strip()} |")
    if rows:
        lines += ["", *header, *rows]
    for name, value in _members(cls):
        function = value.__func__ if isinstance(value, (classmethod, staticmethod)) else value
        if not inspect.isfunction(function):
            continue
        keyword = "async def " if inspect.iscoroutinefunction(function) else "def "
        decorator = (
            "@classmethod\n"
            if isinstance(value, classmethod)
            else "@staticmethod\n"
            if isinstance(value, staticmethod)
            else ""
        )
        lines += ["", f"{'#' * (level + 1)} `{cls.__name__}.{name}`", ""]
        lines += _fenced(
            decorator + signature_text(keyword, name, function, drop_first=not isinstance(value, staticmethod))
        )
        doc = markdown(inspect.getdoc(function))
        if doc:
            lines += ["", doc]
    return lines


