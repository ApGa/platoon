"""Generate the reference pages in ``docs/reference`` from the code.

    python scripts/gen_reference.py            # write docs/reference/{cli,config,api,experimental}.md
    python scripts/gen_reference.py --check    # list the stale pages and exit 1, writing nothing

* ``cli.md``: every ``platoon`` command, from the cyclopts app's own docs (``App.generate_docs``), and the
  ``platoon viz`` subcommands from their argparse parser.
* ``config.md``: every config dataclass or pydantic model reachable from the training config
  (``PlatoonTinkerRLTrainerConfig``) and the evaluation config (``PlatoonEvalConfig``): each key's type,
  default and description.
  It ends with core's task samplers, the levels each serves, and ``pass_rate``'s options, core's group admission
  rules, with ``informative``'s options, core's trainers, with the options of each that takes some, and core's
  credit estimators, with ``keyed``'s options.
* ``api.md``: every name ``platoon`` exports (``platoon.__all__``), with its signature and docstring.
* ``experimental.md``: every name ``platoon.experimental`` exports, the same way.

A field's or attribute's description is its attribute docstring (a string literal right after it), else the
comment block directly above it followed by its trailing comment.  Section rules (``# --- name ---``) and tool
pragmas (``noqa``, ``type:``) are left out.  ``tests/docs/test_reference_up_to_date.py`` fails while a page is
stale.
"""

