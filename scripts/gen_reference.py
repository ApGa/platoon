_RULE = re.compile(r"^-{2,}.*-{2,}$")
_PRAGMA = re.compile(r"^(noqa|type:|pragma|fmt:|ruff:|pyright:|mypy:)")


def member_docs(obj: Any) -> dict[str, str]:
    """``{name: description}`` for the assignments in a class body or module, from their attribute docstrings
    or comments (see the module docstring)."""

    try:
        source = textwrap.dedent(inspect.getsource(obj))
    except (OSError, TypeError):
        return {}
    tree = ast.parse(source)
    body = tree.body if isinstance(obj, types.ModuleType) else typing.cast(ast.ClassDef, tree.body[0]).body
    lines = source.splitlines()
    comments: dict[int, tuple[str, bool]] = {}
    for token in tokenize.generate_tokens(io.StringIO(source).readline):
        if token.type == tokenize.COMMENT:
            row, column = token.start
            comments[row] = (token.string.lstrip("#").strip(), not lines[row - 1][:column].strip())
    docs: dict[str, str] = {}
    for index, node in enumerate(body):
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names = [node.target.id]
        elif isinstance(node, ast.Assign):
            names = [target.id for target in node.targets if isinstance(target, ast.Name)]
        else:
            continue
        following = body[index + 1] if index + 1 < len(body) else None
        if (
            isinstance(following, ast.Expr)
            and isinstance(following.value, ast.Constant)
            and isinstance(following.value.value, str)
        ):
            doc = inspect.cleandoc(following.value.value)
        else:
            block: list[str] = []
            row = node.lineno - 1
            while row in comments and comments[row][1]:
                block.append(comments[row][0])
                row -= 1
            trailing = [
                comments[row][0]
                for row in range(node.lineno, (node.end_lineno or node.lineno) + 1)
                if row in comments and not comments[row][1]
            ]
            parts = [
                line for line in [*reversed(block), *trailing] if not _RULE.match(line) and not _PRAGMA.match(line)
            ]
            doc = " ".join(part for part in parts if part)
        if doc:
            for name in names:
                docs[name] = doc
    return docs


def class_member_docs(cls: type) -> dict[str, str]:
    """:func:`member_docs` over ``cls`` and its bases, the subclass winning."""

    docs: dict[str, str] = {}
    for base in reversed(cls.__mro__):
        if base.__module__ not in ("builtins", "typing") and base is not typing.Generic:
            docs.update(member_docs(base))
    return docs


def markdown(doc: str | None) -> str:
    """A docstring as Markdown: Sphinx roles become code spans and a trailing ``::`` a colon."""

    if not doc:
        return ""
    doc = re.sub(r":(?:py:)?[a-z]+:`[~!]?([^`]+)`", r"`\1`", doc)
    doc = re.sub(r"(?<!`)``([^`]+?)``(?!`)", lambda match: "`" + " ".join(match[1].split()) + "`", doc)
    doc = re.sub(r"(?<=\S)::$", ":", doc, flags=re.MULTILINE)
    return doc.strip()


def cell(text: str | None) -> str:
    """Text for one Markdown table cell: one line, pipes escaped."""

    if not text:
        return ""
    paragraphs = [" ".join(paragraph.split()) for paragraph in markdown(text).split("\n\n")]
    return "<br><br>".join(paragraph for paragraph in paragraphs if paragraph).replace("|", "\\|")


def summary(doc: str | None) -> str:
    """A docstring's first paragraph, on one line."""

    return " ".join(markdown(doc).split("\n\n")[0].split())


def anchor(*parts: str) -> str:
    return "-".join(re.sub(r"[^a-z0-9]+", "-", part.lower()).strip("-") for part in parts)


