def _task_samplers(links: Mapping[type, str]) -> list[str]:
    from platoon.train.samplers import ENTRY_SAMPLERS, RUN_SAMPLERS, PassRateOptions

    lines = [
        "",
        '<a id="task-samplers"></a>',
        "",
        "## Task samplers",
        "",
        "`train.task_sampler` chooses how a run draws its training tasks, and under a run sampler that hands slots to "
        "the entries (`weighted`, and `auto` for a mixture), each entry's `task_sampler` chooses the task that fills "
        "each of its slots. Core's samplers are below; a package an entry names may register others with "
        "`@task_sampler`, and `module:Class` names one ([Write a task sampler](../extending/task-samplers.md)).",
        "",
        "| Sampler | Levels | What it draws | Options |",
        "|---|---|---|---|",
    ]
    for name in dict.fromkeys((*RUN_SAMPLERS, *ENTRY_SAMPLERS)):
        if name not in TASK_SAMPLER_TEXT:
            raise ValueError(
                f"core's task sampler {name!r} has no text in scripts/gen_reference.py's TASK_SAMPLER_TEXT"
            )
        levels = ", ".join(
            level for level, names in (("run", RUN_SAMPLERS), ("entry", ENTRY_SAMPLERS)) if name in names
        )
        options = "[below](#pass-rate-options)" if name == "pass_rate" else "none"
        lines.append(f"| `{name}` | {levels} | {cell(TASK_SAMPLER_TEXT[name])} | {options} |")
    lines += [
        "",
        '<a id="pass-rate-options"></a>',
        "",
        "### `pass_rate`'s options",
        "",
        f"`{PassRateOptions.__module__}.{PassRateOptions.__qualname__}`: the keys of `task_sampler_options` under "
        "`task_sampler: pass_rate`.",
        "",
        markdown(inspect.getdoc(PassRateOptions)),
        "",
        "| Key | Type | Default | Description |",
        "|---|---|---|---|",
    ]
    for item in config_fields(PassRateOptions):
        type_text = _config_type_text(item.annotation, links).replace("|", "\\|")
        lines.append(f"| `{item.name}` | {type_text} | {item.default} | {cell(item.doc)} |")
    return lines


