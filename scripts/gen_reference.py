def _viz_parser() -> argparse.ArgumentParser:
    """The parser ``platoon.visualization.cli.main`` builds, caught before it parses anything."""

    from platoon.visualization import cli as viz_cli

    class Built(Exception):
        pass

    def capture(self: argparse.ArgumentParser, *args: Any, **kwargs: Any) -> Any:
        raise Built(self)

    original = argparse.ArgumentParser.parse_args
    argparse.ArgumentParser.parse_args = capture  # type: ignore[method-assign]
    try:
        viz_cli.main([])
    except Built as built:
        return built.args[0]
    finally:
        argparse.ArgumentParser.parse_args = original  # type: ignore[method-assign]
    raise RuntimeError("platoon.visualization.cli.main returned without building a parser")


def _render_viz() -> str:
    parser = _viz_parser()
    subparsers = next(action for action in parser._actions if isinstance(action, argparse._SubParsersAction))
    helps = {choice.dest: choice.help for choice in subparsers._choices_actions}
    lines = [
        "## platoon viz subcommands",
        "",
        "`platoon viz` opens the trajectory viewer, a terminal UI over the event files that rollouts write under "
        "`<output_dir>/events/`.",
    ]
    for name, sub in subparsers.choices.items():
        actions = [action for action in sub._actions if not isinstance(action, argparse._HelpAction)]
        positionals = [action for action in actions if not action.option_strings]
        usage = ["platoon", "viz", name]
        if any(action.option_strings for action in actions):
            usage.append("[OPTIONS]")
        usage += [_positional_usage(action) for action in positionals]
        lines += [
            "",
            f"### platoon viz {name}",
            "",
            "```console",
            " ".join(usage),
            "```",
            "",
            f"{helps.get(name, '')}.".replace("..", "."),
            "",
            "| Argument | Default | Description |",
            "|---|---|---|",
        ]
        for action in actions:
            if action.option_strings:
                flag = ", ".join(action.option_strings)
                if action.choices:
                    flag += " {" + ",".join(str(choice) for choice in action.choices) + "}"
                elif action.nargs != 0:
                    flag += f" {(action.dest or '').upper()}"
                default = "" if action.default in (None, False) else f"`{action.default}`"
            else:
                flag, default = _positional_usage(action), ""
            lines.append(f"| `{flag}` | {default} | {cell(action.help)} |")
    return "\n".join(lines)


def _positional_usage(action: argparse.Action) -> str:
    metavar = action.metavar if isinstance(action.metavar, str) else None
    name = (metavar or action.dest).upper()
    return {"*": f"[{name} ...]", "+": f"{name} [{name} ...]", "?": f"[{name}]"}.get(str(action.nargs), name)


