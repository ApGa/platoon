    value = getattr(platoon, name)
    if name == "harness":
        from platoon.harness import function

        return render_object("pt.harness", function.harness, function, 3, "pt.")
    if isinstance(value, types.ModuleType):
        lines = [
            "",
            f'<a id="{anchor("pt." + name)}"></a>',
            "",
            f"### `pt.{name}`",
            "",
            markdown(inspect.getdoc(value)),
        ]
        for member in getattr(value, "__all__", ()):
            lines += render_object(f"pt.{name}.{member}", getattr(value, member), value, 4, f"pt.{name}.")
        return lines
    return render_object(f"pt.{name}", value, _defining_module(name, value), 3, "pt.")


